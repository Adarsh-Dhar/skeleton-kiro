"""Filesystem repository for normalized historical sessions.

Layout under ``<data_dir>/historical``::

    fastf1-cache/                     # FastF1's own upstream cache
    sessions/<session_id>/
        manifest.json
        laps.parquet
        weather.parquet
        telemetry/<DRIVER>.parquet    # all laps of that driver, lap_number column
        position/<DRIVER>.parquet
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import pandas as pd

_SAFE = re.compile(r"[^a-z0-9]+")


def slug(text: str) -> str:
    return _SAFE.sub("-", str(text).lower()).strip("-") or "x"


def session_id(year: int, event: str, session_type: str) -> str:
    """Deterministic, path-safe session id."""
    return f"fastf1-{year}-{slug(event)}-{slug(session_type)}"


class HistoricalRepository:
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root)
        self.sessions_dir = self.root / "sessions"
        self.cache_dir = self.root / "fastf1-cache"
        self.sessions_dir.mkdir(parents=True, exist_ok=True)

    def _dir(self, sid: str) -> Path:
        # session ids are generated by session_id(); still guard against traversal
        if "/" in sid or ".." in sid or sid.startswith("."):
            raise ValueError(f"unsafe session id: {sid!r}")
        return self.sessions_dir / sid

    def exists(self, sid: str) -> bool:
        return (self._dir(sid) / "manifest.json").exists()

    def save_session(self, sid: str, manifest: dict, laps: pd.DataFrame, weather: pd.DataFrame,
                     telemetry: dict[str, pd.DataFrame], position: dict[str, pd.DataFrame]) -> Path:
        d = self._dir(sid)
        (d / "telemetry").mkdir(parents=True, exist_ok=True)
        (d / "position").mkdir(parents=True, exist_ok=True)
        tmp = d / "manifest.tmp.json"
        tmp.write_text(json.dumps(manifest, indent=2, default=str))
        if not laps.empty:
            laps.to_parquet(d / "laps.parquet", index=False)
        if not weather.empty:
            weather.to_parquet(d / "weather.parquet", index=False)
        for code, df in telemetry.items():
            if df is not None and not df.empty:
                df.to_parquet(d / "telemetry" / f"{slug(code)}.parquet", index=False)
        for code, df in position.items():
            if df is not None and not df.empty:
                df.to_parquet(d / "position" / f"{slug(code)}.parquet", index=False)
        tmp.replace(d / "manifest.json")  # manifest last: its presence means the session is complete
        return d

    def manifest(self, sid: str) -> dict | None:
        p = self._dir(sid) / "manifest.json"
        return json.loads(p.read_text()) if p.exists() else None

    def list_sessions(self) -> list[dict]:
        out = []
        for d in sorted(self.sessions_dir.iterdir()):
            if not d.is_dir():
                continue
            m = self.manifest(d.name)
            if m:
                out.append({k: m.get(k) for k in ("session_id", "provider", "year", "event", "circuit", "session",
                                                  "session_type", "session_date", "imported_at", "drivers", "channels")})
        return sorted(out, key=lambda m: (m.get("year") or 0, m.get("event") or ""), reverse=True)

    def laps(self, sid: str) -> pd.DataFrame:
        p = self._dir(sid) / "laps.parquet"
        return pd.read_parquet(p) if p.exists() else pd.DataFrame()

    def weather(self, sid: str) -> pd.DataFrame:
        p = self._dir(sid) / "weather.parquet"
        return pd.read_parquet(p) if p.exists() else pd.DataFrame()

    def _driver_file(self, sid: str, kind: str, driver: str) -> Path | None:
        d = self._dir(sid) / kind
        if not d.is_dir():
            return None
        for p in d.glob("*.parquet"):
            if p.stem.upper() == slug(driver).upper():
                return p
        return None

    def telemetry(self, sid: str, driver: str) -> pd.DataFrame:
        p = self._driver_file(sid, "telemetry", driver)
        return pd.read_parquet(p) if p else pd.DataFrame()

    def position(self, sid: str, driver: str) -> pd.DataFrame:
        p = self._driver_file(sid, "position", driver)
        return pd.read_parquet(p) if p else pd.DataFrame()

    @staticmethod
    def records(df: pd.DataFrame, limit: int | None = None) -> list[dict[str, Any]]:
        """DataFrame -> JSON-safe records (NaN -> None), optionally capped to the last ``limit`` rows."""
        if df is None or df.empty:
            return []
        if limit is not None and len(df) > limit:
            df = df.tail(limit)
        # astype(object) first so nullable Int64/boolean NA values become None (JSON-safe),
        # not pd.NA which is not serializable.
        obj = df.astype(object)
        return obj.where(pd.notna(obj), None).to_dict(orient="records")
