def first_paragraph(doc: str | None) -> str:
    return " ".join((inspect.cleandoc(doc or "").split("\n\n")[0]).split()).replace("``", "`")


def describe(name: str) -> list[str]:
    obj = getattr(trialforge, name)
    lines: list[str] = []
    if inspect.isclass(obj):
        lines.append(f"### `{name}`\n")
        lines.append(first_paragraph(obj.__doc__) + "\n")
        if issubclass(obj, pydantic.BaseModel):
            fields = ", ".join(f"`{n}`" for n in obj.model_fields)
            lines.append(f"Fields: {fields}\n")
        members = []
        for mname, member in vars(obj).items():
            if mname.startswith("_"):
                continue
            target = member.fget if isinstance(member, property) else getattr(member, "__func__", member)
            if not inspect.isfunction(target):
                continue
            try:
                sig = str(inspect.signature(target)).replace("(self, ", "(").replace("(self)", "()")
            except (TypeError, ValueError):
                sig = "(...)"
            prefix = "async " if inspect.iscoroutinefunction(target) else ""
            members.append(f"- `{prefix}{mname}{sig}`: {first_paragraph(target.__doc__)}")
        if members and not issubclass(obj, (pydantic.BaseModel, Exception)):
            lines.append("\n".join(members) + "\n")
    elif inspect.isfunction(obj):
        lines.append(f"### `{name}{inspect.signature(obj)}`\n")
        lines.append(first_paragraph(obj.__doc__) + "\n")
    return lines


def render() -> str:
    out = [
        "# TRIALFORGE API reference",
        "",
        f"_Generated by `scripts/gen_api_reference.py` for trialforge {trialforge.__version__} "
        f"(API version {trialforge.API_VERSION}). Do not edit by hand._",
        "",
        "Everything below is importable from the top-level `trialforge` package; those names are the stable public API.",
        "",
    ]
    covered = set()
    for group, names in GROUPS.items():
        out += [f"## {group}", ""]
        for n in names:
            out += describe(n)
            covered.add(n)
    rest = sorted(
        set(trialforge.__all__)
        - covered
        - {"Analyzer", "InMemoryExperimentRepository", "DEFAULT_PLUGINS", "DEFAULT_UNITS", "API_VERSION"}
    )
    if rest:
        out += ["## Other exports", ""]
        for n in rest:
            out += describe(n)
    out += [
        "## Aliases and constants",
        "",
        "- `Analyzer` is an alias of `AnalysisEngine`.",
        "- `InMemoryExperimentRepository()` returns an ephemeral `SQLiteExperimentRepository`.",
        "- `DEFAULT_PLUGINS` / `DEFAULT_UNITS`: process-wide default `PluginRegistry` / `UnitRegistry`.",
        "- `API_VERSION`: major version of the public API contract.",
        "",
    ]
    return "\n".join(out)


